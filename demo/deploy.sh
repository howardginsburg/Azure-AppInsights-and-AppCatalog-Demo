#!/usr/bin/env bash
#
# deploy.sh — Application Observability demo estate
#
# Creates:
#   * 1 resource group          (the entire blast radius — teardown.sh deletes it wholesale)
#   * 1 Log Analytics workspace (deliberately ONE — see doc 02)
#   * 8 workspace-based Application Insights resources, tagged with the doc 05 taxonomy
#   * 1 catalog reference surface (AppCatalog saved function)
#   * 1 portfolio Workbook      (deployed via ARM — the supported path)
#
# Cost: Azure Monitor bills on ingestion, not on resource existence. At demo volume this
# sits inside the workspace free grant. A daily cap is set as a fuse regardless.
#
set -euo pipefail

# Git Bash/MSYS rewrites arguments that look like Unix paths, which corrupts Azure
# resource IDs (/subscriptions/... becomes C:/Program Files/Git/subscriptions/...).
# Harmless no-op on Linux and WSL.
export MSYS_NO_PATHCONV=1
export MSYS2_ARG_CONV_EXCL='*'

RG="${RG:-AppInsightsDemo}"
LOCATION="${LOCATION:-eastus}"
WORKSPACE="${WORKSPACE:-log-obsdemo}"
DAILY_CAP_GB="${DAILY_CAP_GB:-1}"
RETENTION_DAYS="${RETENTION_DAYS:-30}"
ENV_FILE="$(dirname "$0")/.env"

# workload | domain | criticality | owner | tier
ESTATE=(
  "retail-web|Retail|tier1|commerce-team|frontend"
  "retail-api-orders|Retail|tier1|commerce-team|api"
  "retail-api-catalog|Retail|tier2|commerce-team|api"
  "pay-api-gateway|Payments|tier1|payments-team|api"
  "pay-worker-settlement|Payments|tier1|payments-team|worker"
  "cust-api-profile|Customer|tier2|customer-team|api"
  "cust-worker-notify|Customer|tier3|customer-team|worker"
  "shared-api-inventory|Platform|tier1|platform-team|api"
)

say() { printf '\n\033[1;36m==> %s\033[0m\n' "$1"; }
ok()  { printf '    \033[0;32m%s\033[0m\n' "$1"; }

say "Verifying Azure context"
ACCOUNT=$(az account show --query "{user:user.name,sub:name,id:id}" -o json)
echo "$ACCOUNT" | sed 's/^/    /'
SUB_ID=$(echo "$ACCOUNT" | grep -o '"id": *"[^"]*"' | cut -d'"' -f4)

say "Ensuring application-insights CLI extension"
az extension show --name application-insights >/dev/null 2>&1 \
  || az extension add --name application-insights --only-show-errors >/dev/null
ok "present"

say "Creating resource group '$RG' in $LOCATION"
az group create -n "$RG" -l "$LOCATION" --only-show-errors \
  --tags purpose=observability-demo owner=hoginsbu disposable=true >/dev/null
ok "$RG"

say "Creating Log Analytics workspace '$WORKSPACE'"
# ONE workspace for the whole estate. This is the doc 02 thesis made concrete:
# "your design should use the fewest number of workspaces to meet your requirements."
az monitor log-analytics workspace create \
  -g "$RG" -n "$WORKSPACE" -l "$LOCATION" \
  --retention-time "$RETENTION_DAYS" \
  --quota "$DAILY_CAP_GB" \
  --only-show-errors >/dev/null
WS_ID=$(az monitor log-analytics workspace show -g "$RG" -n "$WORKSPACE" --query id -o tsv)
ok "$WORKSPACE (retention ${RETENTION_DAYS}d, daily cap ${DAILY_CAP_GB}GB)"

say "Creating ${#ESTATE[@]} Application Insights resources"
: > "$ENV_FILE"
{
  echo "# Generated by deploy.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# Connection strings for the telemetry simulator. Do not commit."
  echo "DEMO_RESOURCE_GROUP=$RG"
  echo "DEMO_SUBSCRIPTION_ID=$SUB_ID"
  echo "DEMO_WORKSPACE_ID=$WS_ID"
} >> "$ENV_FILE"

for entry in "${ESTATE[@]}"; do
  IFS='|' read -r workload domain criticality owner tier <<< "$entry"
  app="ai-${workload}"

  az monitor app-insights component create \
    --app "$app" -g "$RG" -l "$LOCATION" \
    --workspace "$WS_ID" \
    --application-type web --kind web \
    --tags "domain=$domain" "workload=$workload" "criticality=$criticality" \
           "owner=$owner" "tier=$tier" "catalogKey=$workload" "demo=true" \
    --only-show-errors >/dev/null

  CS=$(az monitor app-insights component show --app "$app" -g "$RG" --query connectionString -o tsv)
  VAR="APPINSIGHTS_$(echo "$workload" | tr 'a-z-' 'A-Z_')"
  echo "${VAR}=${CS}" >> "$ENV_FILE"
  ok "$app  [$domain/$criticality]"
done

# The service catalog is published as a workspace saved function aliased AppCatalog.
# That is ARM metadata, not log data: it has no retention and no TimeGenerated, so it
# never ages out and nothing has to keep re-feeding it. sync-catalog.mjs (below) both
# creates and updates it, so there is no infrastructure to provision here.
#
# The trade-off is that a function knows only *now* -- it cannot answer "who owned this
# service on the day of the incident?". If point-in-time history is ever needed, add a
# custom log table fed by the Logs Ingestion API as a deliberate second component.

say "Publishing service catalog"
if command -v node >/dev/null 2>&1; then
  ( cd "$(dirname "$0")" && node sync-catalog.mjs \
      --rg "$RG" --workspace "$WORKSPACE" --subscription "$SUB_ID" ) | sed 's/^/    /'
else
  echo "    node not found — run 'node sync-catalog.mjs' once available"
fi

say "Deploying portfolio workbook"
WB_TEMPLATE="$(dirname "$0")/workbook-portfolio.json"
# Regenerate first. The workbook definition now reads queries/estate-map.kql at build time,
# so editing that query and running only deploy.sh would otherwise ship a stale map with no
# indication anything was out of date.
if command -v node >/dev/null 2>&1; then
  ( cd "$(dirname "$0")" && node build-workbook.mjs ) | sed 's/^/    /'
else
  echo "    node not found — deploying workbook-portfolio.json as-is"
fi
if [[ -f "$WB_TEMPLATE" ]]; then
  az deployment group create \
    -g "$RG" \
    --name "portfolio-workbook" \
    --template-file "$WB_TEMPLATE" \
    --parameters workbookSourceId="$WS_ID" \
    --only-show-errors --query "properties.provisioningState" -o tsv | sed 's/^/    /'
else
  echo "    (workbook-portfolio.json not found — skipping)"
fi

say "Done"
cat <<EOF
    Resource group : $RG
    Workspace      : $WORKSPACE
    App Insights   : ${#ESTATE[@]} resources
    Catalog        : AppCatalog (saved function)
    Connection strings written to: $ENV_FILE

    Next:  cd simulator && dotnet run -- --backfill-hours 24
    Catalog refresh: node sync-catalog.mjs
    Clean: ./teardown.sh
EOF
