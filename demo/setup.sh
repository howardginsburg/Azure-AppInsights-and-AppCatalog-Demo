#!/usr/bin/env bash
#
# demo/setup.sh: registers the eight demo apps, writes demo/.env with their connection strings
# for the simulator, and loads the demo's business context into the catalog. deploy.sh runs it
# unless DEMO=false. Safe to re-run: existing catalog entries are never overwritten.

source "$(dirname "${BASH_SOURCE[0]}")/../lib/common.sh"

require_az
require_bicep

DEMO_DIR="$REPO_ROOT/demo"
WORKSPACE_ID="$(platform_output workspaceId)"
PLATFORM_LOCATION="$(platform_output location)"
CATALOG_URL="$(platform_output catalogUrl)"

say "Registering the demo apps"
az deployment group create -g "$RG" -n demo-apps \
  --template-file "$(native_path "$DEMO_DIR/apps.bicep")" \
  --parameters workspaceId="$WORKSPACE_ID" location="$PLATFORM_LOCATION" -o none

say "Writing demo/.env"
apps="$(azq deployment group show -g "$RG" -n demo-apps \
  --query "properties.outputs.apps.value[].[name, resourceId]" -o tsv)"
env_file="$DEMO_DIR/.env"
echo "# Generated by demo/setup.sh. Connection strings for the simulator. Do not commit." > "$env_file"
while IFS=$'\t' read -r name id; do
  cs="$(azq resource show --ids "$id" --query properties.ConnectionString -o tsv)"
  printf 'APPINSIGHTS_%s=%s\n' "$(printf '%s' "$name" | tr 'a-z.-' 'A-Z__')" "$cs" >> "$env_file"
  ok "$name"
done <<< "$apps"

say "Loading the demo catalog"
curl -fsS -X POST "$CATALOG_URL/api/catalog/import" -H 'Content-Type: application/json' \
  --data-binary "@$(native_path "$DEMO_DIR/catalog-seed.json")" >&2
echo >&2
